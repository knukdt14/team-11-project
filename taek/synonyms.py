MAX_TERMS = 8       # 너무 많이 붙이면 원래 질문의 의미가 묻힙니다


def expand_query(query: str, table: dict[str, list[str]] | None = None) -> tuple[str, list]:
    """
    질의에 문서 어휘를 덧붙입니다.

    - 부분 문자열로 찾습니다. 한국어는 조사가 붙어서("킥보드로") 정확히 일치하지 않습니다.
    - 이미 질의에 있는 낱말은 다시 붙이지 않습니다.
    - 최대 MAX_TERMS 개까지만 붙입니다.

    반환: (확장된 질의, [(걸린 사용자어, [붙인 문서어]), ...])
    """
    table = SYNONYMS if table is None else table
    added: list[str] = []
    applied: list[tuple[str, list[str]]] = []

    for user_word, doc_words in table.items():
        if user_word not in query:
            continue
        new = [w for w in doc_words if w not in query and w not in added]
        if not new:
            continue
        for w in new:
            if len(added) >= MAX_TERMS:
                break
            added.append(w)
        applied.append((user_word, new))

    if not added:
        return query, []
    return f"{query} {' '.join(added)}", applied


def main() -> None:
    import sys

    if len(sys.argv) < 2:
        raise SystemExit('사용법: python -m taek.synonyms "질문"')
    q = " ".join(sys.argv[1:])
    expanded, applied = expand_query(q)
    print(f"원본 : {q}")
    print(f"확장 : {expanded}")
    if applied:
        print("적용 :")
        for user_word, doc_words in applied:
            print(f"   {user_word} → {', '.join(doc_words)}")
    else:
        print("적용 : (없음)")


if __name__ == "__main__":
    main()
